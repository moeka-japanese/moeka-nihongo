 function choose(host, button) {
  const q = window.KEIGO_QUIZ.find(q => q.id === button.dataset.keigoQuestion);
  const selected = Number(button.dataset.keigoChoice);
  if (!q || !Number.isInteger(selected) || selected < 0 || selected > 2) return;
  answers.set(q.id, selected);
  const card = button.closest('.keigo-question');
  card.querySelectorAll('[data-keigo-choice]').forEach((b, i) => {
   b.setAttribute('aria-pressed', String(i === selected));
   b.classList.toggle('is-correct', i === q.answer);
   b.classList.toggle('is-incorrect', i === selected && i !== q.answer);
  });
  const panel = card.querySelector('.keigo-feedback');
  panel.hidden = false;
  panel.innerHTML = feedback(q, selected);
 }
